		where secondary_filetype='SHPOSTREWARD';
    END IF;
    
	IF (v_Interfaz_Proceso = 'ACTUALIZA_INFORMES_PAY') then
		update ENELEXT.ODX_CODEMAP_CONFIG 
		set INFA_OUTPUT_FILETYPES_OUTBOUND= 'ENEL_PRESTAINSTA_RDO_D_CA_TOTAL_' || to_char(sysdate,'YYYYmmdd_hh24miss')|| '.txt'
		where secondary_filetype='SHPOSTPAY';
    END IF;
   
