			stage IN VARCHAR2,userName IN VARCHAR2,triggerFilename IN VARCHAR2,tenantId IN VARCHAR2,
			salidacontrol out varchar2,informe varchar2 ) IS
v_Interfaz_Proceso nvarchar2(50);  
v_Listado_Informes nvarchar2(500);
