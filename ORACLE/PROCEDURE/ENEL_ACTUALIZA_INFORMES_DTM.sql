	END;
    w_debug('Fin Truncado de la tabla ENEL_COMMI_DTM.', v_contador_debug);

    w_debug('Cargando tabla ENEL_COMMI_DTM. Periodo:'|| iperiod ,  v_contador_debug);

    INSERT INTO ENEL_COMMI_DTM (TENANTID, period,COMMISSIONSEQ, CREDITSEQ, INCENTIVESEQ, ENTRYNUMBER, PIPELINERUNSEQ, PAYEESEQ, POSITIONSEQ, PERIODSEQ, ORIGINTYPEID,PIPELINERUNDATE,
                                VALUE, UNITTYPEFORVALUE, RATEVALUE, UNITTYPEFORRATEVALUE, BUSINESSUNITMAP, PROCESSINGUNITSEQ, UNITTYPEFORENTRYNUMBER, ISPRIVATE, ORDERID, PARTICIPANTE,ESTADO)

    SELECT 
    commi.TENANTID,
    csp.name,
    commi.COMMISSIONSEQ,
    commi.CREDITSEQ,
    commi.INCENTIVESEQ,
    commi.ENTRYNUMBER,
    commi.PIPELINERUNSEQ,
    commi.PAYEESEQ,
    commi.POSITIONSEQ,
    commi.PERIODSEQ,
    commi.ORIGINTYPEID,
    to_char(commi.PIPELINERUNDATE,'DD/MM/YYYY hh24:mi:ss'),
    TRIM(replace(to_char(commi.VALUE , '9999999999990D99'), '.', ',')),
    commi.UNITTYPEFORVALUE,
    commi.RATEVALUE,
    commi.UNITTYPEFORRATEVALUE,
    commi.BUSINESSUNITMAP,
    commi.PROCESSINGUNITSEQ,
    commi.UNITTYPEFORENTRYNUMBER,
    commi.ISPRIVATE,
    ordtxn.ORDERID,
    pos.NAME,
    case 
    when iInterfaz ='ACTUALIZA_INFORMES_POST' or iInterfaz ='ACTUALIZA_INFORMES_POST_TF' or iInterfaz = 'ACTUALIZA_INFORMES_POST_ALIADO' then 'Liquidado'
    else 'Pte Liquidar'
    end as Estado

	from cs_incentive csi
        INNER JOIN CS_COMMISSION COMMI
            ON COMMI.INCENTIVESEQ=CSI.INCENTIVESEQ
            AND CSI.PERIODSEQ=COMMI.PERIODSEQ
		inner join cs_period csp
			on csp.periodseq=csi.periodseq
			and csp.removedate = v_eot
			and csp.name=iperiod
		-- MPR se incluye el cruce con BU para informar el nombre de la misma
		INNER JOIN CS_PROCESSINGUNIT BU 
			ON CSI.processingunitseq = BU.processingunitseq
          inner join cs_position pos
            on POS.RULEELEMENTOWNERSEQ=commi.positionseq
            and pos.payeeseq=csi.payeeseq
            and pos.REMOVEDATE = '01/01/2200'
            AND pos.TENANTID = 'ENEL' 
            AND pos.EFFECTIVESTARTDATE <= csp.startdate             
			AND pos.EFFECTIVEENDDATE >= csp.enddate
        inner join cs_credit cre
            on cre.creditseq=commi.creditseq
            and cre.periodseq=commi.periodseq
        
        left JOIN cs_salestransaction ETT 
            ON cre.salesorderseq=ETT.salesorderseq
             and cre.compensationdate=ETT.compensationdate
        
        left JOIN cs_salesorder ordtxn
			ON ETT.salesorderseq = ordtxn.salesorderseq
			AND ordtxn.removedate = '01/01/2200'
			AND ETT.tenantid = 'ENEL'
			AND ordtxn.processingunitseq = ETT.processingunitseq
			AND ETT.modelseq = 0
			AND ETT.processingunitseq = 38280596832649318
			AND ordtxn.tenantid = ETT.tenantid

	where 
		csi.processingunitseq=iprocessingunitseq
        AND CSI.NAME LIKE 'C%'
        and 0=(select count(commissionseq) from enel_commi_dtm where commi.commissionseq=commissionseq);

    filas := sql%rowcount;
    COMMIT;

    w_debug('Fin Carga de la tabla ENEL_COMMI_DTM: '|| to_char(filas) || ' filas.', v_contador_debug);
    dbms_stats.gather_table_stats(ownname => 'ENELEXT',tabname => 'ENEL_COMMI_DTM',estimate_percent => dbms_stats.auto_sample_size,degree => dbms_stats.default_degree,cascade => true);

    --EXECUTE IMMEDIATE 'ANALYZE TABLE ENELEXT.ENEL_INCEN_DTM COMPUTE STATISTICS FOR ALL INDEXES';
